-- Which recent migrations (phase124 – phase150) are applied on this database?
-- READ-ONLY: it only looks at the schema. Paste into the Supabase SQL Editor.
-- One row per migration; applied = false means its file still needs running,
-- in phase order (each file's own pre-check / verify query applies).
WITH fn AS (SELECT proname, prosrc FROM pg_proc WHERE pronamespace = 'public'::regnamespace),
     col AS (SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = 'public'),
     trg AS (SELECT tgname FROM pg_trigger WHERE NOT tgisinternal),
     con AS (SELECT conname, pg_get_constraintdef(oid) AS def FROM pg_constraint),
     rules AS (SELECT def FROM con WHERE conname = 'approval_rules_doc_type_check')
SELECT phase, what, applied FROM (VALUES
  (124, 'custom roles can hold permissions',
        NOT EXISTS (SELECT 1 FROM con WHERE conname = 'role_permissions_role_check')),
  (125, 'payroll / leave / gratuity can post',
        EXISTS (SELECT 1 FROM con WHERE conname = 'journal_entries_source_type_check' AND def LIKE '%payroll_run%')),
  (126, 'fixed asset purchase (New Asset buys on bill / expense)',
        to_regclass('public.fixed_asset_purchases') IS NOT NULL),
  (127, 'fixed asset quantity / partial disposal / void',
        EXISTS (SELECT 1 FROM col WHERE table_name = 'fixed_assets' AND column_name = 'quantity')),
  (128, 'partial disposal audit action',
        EXISTS (SELECT 1 FROM fn WHERE proname = 'dispose_fixed_asset_partial')),
  (129, 'one staff identity (salespeople ↔ employees)',
        EXISTS (SELECT 1 FROM col WHERE table_name = 'salespeople' AND column_name = 'employee_id')),
  (130, 'salespeople linked to employees',
        EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'salespeople'
                  AND column_name = 'employee_id' AND is_nullable = 'NO')),
  (131, 'payroll admin-only + locks',
        EXISTS (SELECT 1 FROM fn WHERE proname = 'void_payroll_run')),
  (132, 'tax registration number validation',
        EXISTS (SELECT 1 FROM trg WHERE tgname ILIKE '%tax_registration%' OR tgname ILIKE '%trn%')),
  (133, 'Help & Support tickets',
        EXISTS (SELECT 1 FROM fn WHERE proname = 'support_create_ticket')),
  (134, 'write-permission gaps closed',
        EXISTS (SELECT 1 FROM trg WHERE tgname = 'document_sequences_guard')),
  (135, 'legal agreements / Terms acceptance',
        EXISTS (SELECT 1 FROM fn WHERE proname = 'accept_legal')),
  (136, 'guarded company deletion (platform)',
        EXISTS (SELECT 1 FROM fn WHERE proname = 'platform_delete_company')),
  (137, 'asset purchase document guard',
        EXISTS (SELECT 1 FROM trg WHERE tgname = 'debit_notes_asset_purchase_guard')),
  (138, 'document activity (created_by, status log)',
        EXISTS (SELECT 1 FROM col WHERE table_name = 'invoices' AND column_name = 'created_by')),
  (139, 'Razorpay / payment-provider switch',
        EXISTS (SELECT 1 FROM fn WHERE proname = 'set_billing_provider')),
  (140, 'invite links',
        EXISTS (SELECT 1 FROM fn WHERE proname = 'get_invite_preview')),
  (141, 'admin insights (/admin, sign-up alerts)',
        EXISTS (SELECT 1 FROM fn WHERE proname = 'admin_list_users')),
  (142, 'admin Control Center (overview range, businesses)',
        EXISTS (SELECT 1 FROM fn WHERE proname = 'admin_overview_range')),
  (143, 'currency display (code / symbol)',
        EXISTS (SELECT 1 FROM col WHERE table_name = 'companies' AND column_name = 'currency_display')),
  (144, 'Team: reporting lines, login links, code format',
        EXISTS (SELECT 1 FROM col WHERE table_name = 'employees' AND column_name = 'reports_to_id')),
  (145, 'Approvals engine + purchasing',
        to_regclass('public.approval_requests') IS NOT NULL),
  (146, 'Approvals: sales documents',
        EXISTS (SELECT 1 FROM rules WHERE def LIKE '%customer_receipt%')),
  (147, 'Approvals: adjustments, bank transfers, assets, payroll',
        EXISTS (SELECT 1 FROM rules WHERE def LIKE '%payroll_run%')),
  (148, 'stock transfers can be confirmed (fix)',
        EXISTS (SELECT 1 FROM fn WHERE proname = 'confirm_stock_transfer' AND prosrc LIKE '%status = ''completed''%')),
  (149, 'Approvals: stock transfers',
        EXISTS (SELECT 1 FROM rules WHERE def LIKE '%stock_transfer%')),
  (150, 'Approvals: manual journal entries',
        EXISTS (SELECT 1 FROM trg WHERE tgname = 'journal_entries_approval_guard'))
) AS v(phase, what, applied)
ORDER BY phase;
